export const ICON_NAMES = Object.freeze(Object.keys(ICONS));

export function hasIcon(name) {
  return typeof name === "string" && Object.prototype.hasOwnProperty.call(ICONS, name);
}

export function Icon({ name, size, title, className = "", style, ...rest }) {
  const def = ICONS[name];
  if (!def) return null;
  const dim = size == null ? undefined : size;
  // .flow-icon 의 width/height:1em 이 속성값을 덮으므로 size 는 인라인 스타일로 준다.
  const sized = dim == null ? style : { width: dim, height: dim, ...style };
  return (
    <svg
      viewBox="0 0 20 20"
      width={dim}
      height={dim}
      className={`flow-icon${className ? ` ${className}` : ""}`}
      style={sized}
      role={title ? "img" : undefined}
      aria-hidden={title ? undefined : true}
      aria-label={title || undefined}
      focusable="false"
      data-icon={name}
      {...rest}
    >
      {title && <title>{title}</title>}
      {def.t && <path className="flow-icon__tone" d={def.t.join("")} />}
      {def.l && <path className="flow-icon__line" d={def.l.join("")} />}
      {def.s && <path className="flow-icon__solid" d={def.s.join("")} />}
    </svg>
  );
}

/** 아이콘 + 글자 한 덩어리. flex 부모 안에서도 간격이 유지된다. */
export function IconLabel({ icon, children, size, className = "", style, iconStyle, title }) {
  return (
    <span className={`flow-icon-label${className ? ` ${className}` : ""}`} style={style} title={title}>
      <Icon name={icon} size={size} style={iconStyle} />
      {children != null && children !== "" && <span className="flow-icon-label__text">{children}</span>}
    </span>
  );
}

/** 이모지 신호등(🟢🟡🔴⚪🟣🔵) 대체 — 토큰 색 원. */
export function StatusDot({ tone = "neutral", title, className = "", style }) {
  return (
    <span
      className={`flow-status-dot${className ? ` ${className}` : ""}`}
      data-tone={tone}
      title={title}
      role={title ? "img" : undefined}
      aria-label={title || undefined}
      aria-hidden={title ? undefined : true}
      style={style}
    />
  );
}

/** 문자열 이름이면 아이콘으로, 이미 노드면 그대로 — EmptyState/Feedback 의 icon prop 용. */
export function renderIcon(icon, props) {
  if (hasIcon(icon)) return <Icon name={icon} {...props} />;
  return icon;
}
