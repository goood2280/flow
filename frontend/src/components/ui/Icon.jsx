function polarPath(points) {
  return points.map(([x, y], i) => `${i ? "L" : "M"}${x.toFixed(2)} ${y.toFixed(2)}`).join("") + "Z";
}

function gearPath(cx, cy, outer, inner, teeth) {
  const pts = [];
  const step = (Math.PI * 2) / teeth;
  const top = step * 0.17;
  const base = step * 0.29;
  for (let i = 0; i < teeth; i += 1) {
    const a = i * step - Math.PI / 2;
    for (const [ang, r] of [[a - base, inner], [a - top, outer], [a + top, outer], [a + base, inner]]) {
      pts.push([cx + Math.cos(ang) * r, cy + Math.sin(ang) * r]);
    }
  }
  return polarPath(pts);
}

function starPath(cx, cy, outer, inner) {
  const pts = [];
  for (let i = 0; i < 10; i += 1) {
    const a = (i * Math.PI) / 5 - Math.PI / 2;
    const r = i % 2 ? inner : outer;
    pts.push([cx + Math.cos(a) * r, cy + Math.sin(a) * r]);
  }
  return polarPath(pts);
}

